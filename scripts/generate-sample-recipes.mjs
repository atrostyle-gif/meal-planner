function r(name, category, course, tags, servings, minutes, memo, ings, steps) {
  return { name, category, course, tags, servings, minutes, memo, ings, steps };
}

// バリデーション
const names = new Set();
const courseCount = Object.fromEntries(COURSES.map((c) => [c, 0]));
for (const item of recipes) {
  if (names.has(item.name)) {
    throw new Error(`重複: ${item.name}`);
  }
  names.add(item.name);
  if (!COURSES.includes(item.course)) {
    throw new Error(`不正なcourse: ${item.name} ${item.course}`);
  }
  courseCount[item.course] += 1;
  if (item.ings.length < 3 || item.ings.length > 10) {
    throw new Error(`材料数不正: ${item.name} (${item.ings.length})`);
  }
  if (item.steps.length < 4 || item.steps.length > 8) {
    throw new Error(`手順数不正: ${item.name} (${item.steps.length})`);
  }
  if (item.tags.length < 2 || item.tags.length > 5) {
    throw new Error(`タグ数不正: ${item.name}`);
  }
  if (item.servings < 2 || item.servings > 6) {
    throw new Error(`人数不正: ${item.name}`);
  }
  if (item.minutes < 5 || item.minutes > 90) {
    throw new Error(`時間不正: ${item.name}`);
  }
}

if (recipes.length < 80) {
  throw new Error(`件数不足: ${recipes.length}`);
}

function esc(value) {
  return JSON.stringify(value);
}

function renderIngredient(ing) {
  const [name, quantity, unit, type = "normal"] = ing;
  const q = quantity === null ? "null" : String(quantity);
  return `        {
          id: crypto.randomUUID(),
          name: ${esc(name)},
          quantity: ${q},
          unit: ${esc(unit)},
          note: "",
          ingredientType: ${esc(type)},
        }`;
}

function renderRecipe(item) {
  const memoLine = item.memo
    ? `\n      memo: ${esc(item.memo)},`
    : "";
  return `    {
      id: crypto.randomUUID(),
      name: ${esc(item.name)},
      category: ${esc(item.category)},
      course: ${esc(item.course)},
      tags: ${esc(item.tags)},
      servings: ${item.servings},
      cookingTimeMinutes: ${item.minutes},${memoLine}
      isSample: true,
      ingredients: [
${item.ings.map(renderIngredient).join(",\n")},
      ],
      steps: [
${item.steps
  .map(
    (text, i) => `        {
          id: crypto.randomUUID(),
          order: ${i + 1},
          text: ${esc(text)},
        }`,
  )
  .join(",\n")},
      ],
      createdAt: now,
      updatedAt: now,
    }`;
}

const file = `import type { Recipe } from "@/types/recipe";

/**
 * 初回起動時・resetSampleRecipes() で投入する検証用サンプルレシピ。
 * すべて isSample: true。removeSampleRecipes() で一括削除できる。
 */
export function createSampleRecipes(now: string = new Date().toISOString()): Recipe[] {
  return [
${recipes.map(renderRecipe).join(",\n")},
  ];
}

/** サンプルレシピ件数（検証用） */
export const SAMPLE_RECIPE_COUNT = ${recipes.length} as const;
`;

