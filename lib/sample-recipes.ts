import { resolveNutritionFields } from "@/lib/recipe-nutrition";
import type { Recipe } from "@/types/recipe";

type SampleDraft = Omit<
  Recipe,
  | "calories"
  | "protein"
  | "fat"
  | "carbohydrates"
  | "salt"
  | "vegetables"
  | "proteinType"
  | "season"
  | "difficulty"
  | "favoriteScore"
  | "healthyScore"
>;

function finalizeSample(sample: SampleDraft): Recipe {
  const nutrition = resolveNutritionFields(sample as unknown as Record<string, unknown>, {
    name: sample.name,
    tags: sample.tags,
    category: sample.category,
  });
  return { ...sample, ...nutrition };
}

